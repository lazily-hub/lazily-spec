KT_TARGET = {"package": "io.github.lazily", "variant_fields": {"CausalReceipts": "batch"}}


def test_kotlin_backend_lowering() -> None:
    out = wire_codegen.render_kotlin(_surface(RECEIPTS), KT_TARGET)
    assert out.startswith("// @generated by lazily-spec scripts/wire_codegen.py. DO NOT EDIT.\n")
    assert "\npackage io.github.lazily\n" in out
    # u64 lowers to ULong, so a negative generation is unrepresentable.
    assert "    val generation: ULong,\n" in out
    assert "    val reason: String? = null,\n" in out
    assert "    val receipts: List<CausalReceipt> = emptyList(),\n" in out
    # Required-nullable fields are always emitted, as `null` when absent.
    assert 'put("reason", reason?.let { JsonPrimitive(it) } ?: JsonNull)' in out
    # The envelope is lowered as a sealed interface; the variant field name comes from the target.
    assert "sealed interface ReceiptMessage {" in out
    assert "    data class CausalReceiptsMessage(\n        val batch: CausalReceipts,\n" in out
    # Strict decoding: exact key set, min_length checked at construction.
    assert 'val obj = receiptsWireObject("CausalReceipt", element, FIELDS)' not in out
    assert 'val obj = tWireObject("CausalReceipt", element, FIELDS)' in out
    assert 'require(receiptId.length >= 1) { "receipt_id must be a non-empty string" }' in out
    assert "@file:OptIn(ExperimentalSerializationApi::class)" in out


def test_kotlin_backend_default_variant_field_and_keywords() -> None:
    out = wire_codegen.render_kotlin(_surface(RECEIPTS), {"package": "p"})
