def test_go_backend_lowering() -> None:
    out = wire_codegen.render_go(_surface(RECEIPTS), {"package": "lazily"})
    assert out.startswith("// Code generated by lazily-spec scripts/wire_codegen.py. DO NOT EDIT.\n")
    assert "\npackage lazily\n" in out
    assert '\tGeneration uint64 `json:"generation"`\n' in out
    assert '\tReason *string `json:"reason"`\n' in out
    assert "func (v *ReceiptOutcome) UnmarshalJSON(b []byte) error {" in out
    # Required lists never marshal as null.
    assert "\t\tw.Receipts = []CausalReceipt{}\n" in out
    # Envelopes are not lowered for Go.
    assert "ReceiptMessage" not in out
    # Records decode strictly: exact key set, case-sensitive.
    assert "func (r *CausalReceipt) UnmarshalJSON(data []byte) error {" in out
    # The helper is named per surface (here `t`) so several generated files share a package.
    assert "func tCheckWireFields(name string, data []byte, fields []string) error {" in out
    assert '"reason", "payload_hash"}); err != nil {' in out.replace("\n", "")


PY_TARGET = {
    "semantics_module": "._receipt_semantics",
    "mixins": {"ReceiptOutcome": "ReceiptOutcomeSemantics", "CausalReceipts": "CausalReceiptsSemantics"},
}


def _exec_python(out: str) -> dict:
    """Execute generated Python with stand-in semantics mixins."""
    module = out.replace(
        "from ._receipt_semantics import CausalReceiptsSemantics, ReceiptOutcomeSemantics\n",
        "class CausalReceiptsSemantics:\n    __slots__ = ()\n\n\nclass ReceiptOutcomeSemantics:\n    __slots__ = ()\n",
    )
    generated = types.ModuleType("receipts_gen")
    sys.modules[generated.__name__] = generated
    try:
        exec(compile(module, "<generated>", "exec"), generated.__dict__)
    finally:
        del sys.modules[generated.__name__]
    return generated.__dict__


def test_python_backend_lowering() -> None:
    out = wire_codegen.render_python(_surface(RECEIPTS), PY_TARGET)
    assert out.startswith("# @generated by lazily-spec scripts/wire_codegen.py. DO NOT EDIT.\n")
    assert "class ReceiptOutcome(ReceiptOutcomeSemantics, Enum):" in out
    assert "class CausalReceipts(CausalReceiptsSemantics):" in out
    assert "    reason: str | None = None\n" in out
    assert "    receipts: list[CausalReceipt] = field(default_factory=list)\n" in out
    # The envelope lowers onto its single variant record.
    assert 'return {"CausalReceipts": body}' in out
    assert "class ReceiptMessage" not in out


def test_python_backend_decodes_strictly() -> None:
    ns = _exec_python(wire_codegen.render_python(_surface(RECEIPTS), PY_TARGET))
    receipt = {
        "receipt_id": "r",
        "causation_id": "c",
        "observer": "o",
        "generation": 1,
        "outcome": "applied",
        "reason": None,
        "payload_hash": None,
    }
    frame = {"CausalReceipts": {"receipts": [receipt]}}
    assert ns["CausalReceipts"].from_wire(frame).to_wire() == frame
    for bad, message in [
        ({k: v for k, v in receipt.items() if k != "reason"}, "missing field 'reason'"),
        ({**receipt, "extra": 1}, "unknown field 'extra'"),
        ({**receipt, "generation": -1}, "generation must be in"),
        ({**receipt, "generation": True}, "unsigned integer"),
        ({**receipt, "outcome": "done"}, "unknown ReceiptOutcome"),
    ]:
        with pytest.raises(ValueError, match=message):
            ns["CausalReceipt"].from_wire(bad)


