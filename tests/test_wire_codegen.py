def test_check_reports_sibling_drift(tmp_path, monkeypatch, capsys) -> None:
    for repo in ("lazily-rs", "lazily-go", "lazily-py"):
        (tmp_path / repo).mkdir()
    monkeypatch.setattr(wire_codegen, "WORKSPACE_SRC", tmp_path)
    assert wire_codegen.main(["--check"]) == 1
    assert "drift: receipts:rust" in capsys.readouterr().err

    model = wire_codegen.build_model()
    for _label, _repo, dest, content in wire_codegen.generated_targets(
        model, wire_codegen.load_manifest(), tmp_path
    ):
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_text(content)
    assert wire_codegen.main(["--check"]) == 0

    go_file = tmp_path / "lazily-go" / "receipts_wire_gen.go"
    go_file.write_text(go_file.read_text().replace("uint64", "int64"))
    assert wire_codegen.main(["--check"]) == 1
    assert "drift: receipts:go" in capsys.readouterr().err


def test_check_reports_absent_siblings_as_staged(tmp_path, monkeypatch, capsys) -> None:
    monkeypatch.setattr(wire_codegen, "WORKSPACE_SRC", tmp_path)
    assert wire_codegen.main(["--check"]) == 0
    assert "staged: receipts:rust" in capsys.readouterr().out
    assert wire_codegen.main(["--check", "--require-all"]) == 1
